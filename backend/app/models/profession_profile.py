import uuid
from sqlalchemy import Column, Integer, String, JSON, DateTime, Text
from sqlalchemy.sql import func
from app.core.database import Base


class ProfessionProfile(Base):
    """
    RAG domain knowledge reference profiles.
    Stores domain standards, margin benchmarks, operational red flags,
    and the checklist of required information for underwriting personal discussion.
    (Note: Follow-up question banks are deliberately NOT stored here;
    they are dynamically generated by Node 6 of the LangGraph agent).
    """
    __tablename__ = "profession_profiles"

    id = Column(Integer, primary_key=True, autoincrement=True)
    sub_profile = Column(String(50), nullable=False, unique=True, index=True)
    # Matches Applicant.sub_profile / business_category (e.g. RETAIL, MANUFACTURING, SERVICES, SALARIED_PRIVATE, SALARIED_GOVT)
    display_name = Column(String(100), nullable=False)
    overview = Column(Text, nullable=False)
    benchmark_margins_json = Column(JSON, nullable=False)
    # e.g. {"gross_margin_pct": [8, 15], "net_margin_pct": [4, 10], "inventory_turns_days": 30}
    required_info_checklist_json = Column(JSON, nullable=False)
    # e.g. ["credit_ledger_recovery_cycle", "supplier_payment_terms", "daily_cash_sales", "seasonal_swing_pattern"]
    red_flags_json = Column(JSON, nullable=False)
    # e.g. ["turnover claim inconsistent with visible stock"]
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(DateTime(timezone=True), onupdate=func.now(), nullable=True)
